"""Generate Sources/RNGCore/Tables.swift from the data cells of mhxx-rng.ipynb.

The notebook comes from https://github.com/jasmithc/mhgu-rng (an English translation of
https://github.com/apmnnn/mhxx-rng). Run from the repository root:

    python3 tools/gen_tables.py path/to/mhxx-rng.ipynb
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
import sys
if len(sys.argv) < 2 or not pathlib.Path(sys.argv[1]).is_file():
    sys.exit('usage: python3 %s path/to/mhxx-rng.ipynb\n'
             '(get the notebook from https://github.com/jasmithc/mhgu-rng)' % pathlib.Path(sys.argv[0]).name)
NB = pathlib.Path(sys.argv[1])
OUT = HERE.parent / 'Sources' / 'RNGCore' / 'Tables.swift'

cells = json.loads(NB.read_text())['cells']
src = {}
for c in cells:
    text = ''.join(c['source'])
    for tag in ('# @title 1st', '# @title 3rd'):
        if text.startswith(tag):
            src[tag] = text

ns = {}
exec(src['# @title 1st'], ns)
exec(src['# @title 3rd'], ns)


def swift_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def ints(a):
    return '[' + ', '.join(str(v) for v in a) + ']'


def pairs(a):
    return '[' + ', '.join(f'({p}, {q})' for p, q in a) + ']'


def triples(a):
    return '[' + ', '.join(f'({p}, {q}, {r})' for p, q, r in a) + ']'


lines = ['// GENERATED by tools/gen_tables.py from mhxx-rng.ipynb. Do not edit by hand.', '']

lines.append('public let charmKindTables: [CharmTables] = [')
for setter in ('set_blue', 'set_red', 'set_yellow', 'set_white'):
    ns[setter]()
    lines.append('  CharmTables(')
    lines.append(f'    skill1: {ints(ns["skill1"])},')
    lines.append(f'    sp1: {pairs(ns["sp1"])},')
    lines.append(f'    skill2: {ints(ns["skill2"])},')
    lines.append(f'    sp2: {pairs(ns["sp2"])},')
    lines.append(f'    slotValue: {triples(ns["slotvalue"])},')
    lines.append(f'    th: {ns["th"]},')
    lines.append(f'    kind: {ns["kind"]}),')
lines.append(']')
lines.append('')

DEVIANTS = ['Redhelm', 'Snowbaron', 'Stonefist', 'Drilltusk', 'Dreadqueen', 'Crystalbeard',
            'Silverwind', 'Deadeye', 'Dreadking', 'Thunderlord', 'Grimclaw', 'Hellblade',
            'Nightcloak', 'Rustrazor', 'Soulseer', 'Boltreaver', 'Elderfrost', 'Bloodbath']


def fix_en(skill):
    """Make English names unambiguous. Both slots use this one list, so a skill always
    has the same name in slot 1 and slot 2. The deviant skills (143-160 and their X
    versions 161-178) get a "Soul" suffix so that, for example, the deviant Deadeye
    skill is not confused with the gunner skill Dead Eye (65)."""
    skill = list(skill)
    assert skill[150] == 'Deadeye' and skill[178] == 'Bloodbath X'
    for i, name in enumerate(DEVIANTS):
        skill[143 + i] = f'{name} Soul'
        skill[161 + i] = f'{name} Soul X'
    skill[skill.index('Reaload Spd')] = 'Reload Spd'
    assert len(set(skill)) == len(skill), 'duplicate English skill names'
    return skill


lines.append('public let languageTables: [Language: LanguageTables] = [')
for lang, setter in (('en', 'set_en'), ('ja', 'set_ja'), ('zh', 'set_zh')):
    ns[setter]()
    if lang == 'en':
        ns['skill'] = fix_en(ns['skill'])
        ns['skill_width'] = ' <19'   # fit the longer "... Soul X" names
        ns['noskill'] = ' ' * 19 + '----'
    lines.append(f'  .{lang}: LanguageTables(')
    lines.append('    skill: [' + ', '.join(swift_str(s) for s in ns['skill']) + '],')
    lines.append('    origin: [' + ', '.join(swift_str(s) for s in ns['origin']) + '],')
    lines.append('    kinds: [' + ', '.join(swift_str(s) for s in ns['kinds']) + '],')
    lines.append('    melding: [' + ', '.join(swift_str(s) for s in ns['melding']) + '],')
    lines.append(f'    kindWidth: {swift_str(ns["kind_width"])},')
    lines.append(f'    noSkill: {swift_str(ns["noskill"])},')
    lines.append(f'    skillWidth: {swift_str(ns["skill_width"])}),')
lines.append(']')
lines.append('')

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text('\n'.join(lines))
print('wrote', OUT)
